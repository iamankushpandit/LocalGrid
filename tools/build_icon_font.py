#!/usr/bin/env python3
"""Build the handheld's own two icons as an lg_draw font (D55): a handheld, and the LocalGrid mark.

The UI fonts carry Font Awesome's icons, and neither of these is among them. They are drawn here from
their shapes, the way ui_lock.c draws the logo: each pixel's coverage comes from its distance to the
shape, so the edges are smooth at 16 px. No download and no other tool is needed.

  python tools/build_icon_font.py             write components/lg_draw/fonts/lg_font_icons_16.c
  python tools/build_icon_font.py --preview   print the two glyphs as text, to look at

The generated font is committed. The code points are in the Unicode private use area and are named in
components/lg_draw/include/lg_font.h (LG_ICON_HANDHELD, LG_ICON_GRID); keep the two in step.
"""
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "components" / "lg_draw" / "fonts" / "lg_font_icons_16.c"
FIRST = 0xE000          # LG_ICON_HANDHELD; LG_ICON_GRID follows
LINE_HEIGHT = 18        # as lg_font_montserrat_16, beside whose letters these sit
BASE_LINE = 3
SUB = 4                 # samples per pixel edge


def clamp(x):
    return 0.0 if x < 0.0 else 1.0 if x > 1.0 else x


def seg(px, py, ax, ay, bx, by):
    vx, vy = bx - ax, by - ay
    t = clamp(((px - ax) * vx + (py - ay) * vy) / (vx * vx + vy * vy))
    return math.hypot(px - (ax + t * vx), py - (ay + t * vy))


def rounded(px, py, x0, y0, x1, y1, r):
    """Signed distance to a rounded rectangle: negative inside."""
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    qx = abs(px - cx) - ((x1 - x0) / 2 - r)
    qy = abs(py - cy) - ((y1 - y0) / 2 - r)
    return math.hypot(max(qx, 0.0), max(qy, 0.0)) + min(max(qx, qy), 0.0) - r


def handheld(x, y):
    """A handheld seen from the front: a case, its screen left open, and the dot below it. 10 x 16."""
    case = rounded(x, y, 0.5, 0.5, 9.5, 15.5, 2.0)
    screen = rounded(x, y, 2.0, 2.5, 8.0, 11.5, 0.5)
    dot = math.hypot(x - 5.0, y - 13.4) - 0.95
    ink = case <= 0.0 and screen > 0.0 and dot > 0.0
    return 1.0 if ink else 0.0


def grid(x, y):
    """The LocalGrid mark without its tile: three APs joined in a tent, radio waves over the top one. 16 x 16."""
    top, left, right = (8.0, 7.6), (2.2, 13.8), (13.8, 13.8)
    d = min(seg(x, y, *top, *left), seg(x, y, *left, *right), seg(x, y, *right, *top))
    if d <= 0.55:
        return 1.0
    for nx, ny in (top, left, right):
        if math.hypot(x - nx, y - ny) <= 2.0:
            return 1.0
    dx, dy = x - top[0], y - top[1]
    if dy < 0.0 and abs(dx) <= -dy * 1.15:           # the upper wedge only, as in the mark
        r = math.hypot(dx, dy)
        if abs(r - 4.4) <= 0.6 or abs(r - 7.0) <= 0.6:
            return 1.0
    return 0.0


GLYPHS = [("handheld", handheld, 10, 16), ("grid", grid, 16, 16)]


def raster(shape, w, h):
    rows = []
    for py in range(h):
        row = []
        for px in range(w):
            total = 0.0
            for sy in range(SUB):
                for sx in range(SUB):
                    total += shape(px + (sx + 0.5) / SUB, py + (sy + 0.5) / SUB)
            row.append(int(round(total / (SUB * SUB) * 15.0)))
        rows.append(row)
    return rows


def pack(rows):
    """4 bits per pixel, the high nibble first, no row padding: what lg_draw's glyph reader expects."""
    nibbles = [v for row in rows for v in row]
    if len(nibbles) % 2:
        nibbles.append(0)
    return [(nibbles[i] << 4) | nibbles[i + 1] for i in range(0, len(nibbles), 2)]


def main():
    rendered = [(name, w, h, raster(shape, w, h)) for name, shape, w, h in GLYPHS]
    if "--preview" in sys.argv:
        for name, w, h, rows in rendered:
            print(name)
            for row in rows:
                print("  " + "".join(" .:-=+*#%@@@@@@@"[v] for v in row))
        return 0
    bitmap, dsc = [], ["    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id 0: none */"]
    for name, w, h, rows in rendered:
        dsc.append("    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = 0, .ofs_y = -2} /* %s */"
                   % (len(bitmap), (w + 1) * 16, w, h, name))
        bitmap += pack(rows)
    lines = ["/*",
             " * lg_font_icons_16.c - the handheld's own icons, generated by tools/build_icon_font.py.",
             " * Do not edit: change the shapes in the tool and run it again.",
             " */",
             '#include "lg_font.h"',
             "",
             "static const uint8_t glyph_bitmap[] = {"]
    for i in range(0, len(bitmap), 12):
        lines.append("    " + ", ".join("0x%02x" % b for b in bitmap[i:i + 12]) + ",")
    lines += ["};", "", "static const lg_glyph_t glyph_dsc[] = {", ",\n".join(dsc), "};", "",
              "static const lg_font_cmap_t cmaps[] = {",
              "    {",
              "        .range_start = 0x%X, .range_length = %d, .glyph_id_start = 1," % (FIRST, len(GLYPHS)),
              "        .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, "
              ".type = LG_FONT_CMAP_FORMAT0_TINY",
              "    }",
              "};", "",
              "const lg_font_t lg_font_icons_16 = {",
              "    .bitmap = glyph_bitmap,",
              "    .glyphs = glyph_dsc,",
              "    .cmaps = cmaps,",
              "    .cmap_num = 1,",
              "    .bpp = 4,",
              "    .line_height = %d," % LINE_HEIGHT,
              "    .base_line = %d," % BASE_LINE,
              "};", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote %s: %d glyphs, %d bytes of bitmap" % (OUT.relative_to(ROOT), len(GLYPHS), len(bitmap)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
